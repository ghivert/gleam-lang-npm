import * as assert from 'node:assert/strict'
import * as crypto from 'node:crypto'
import * as fs from 'node:fs'
import * as path from 'node:path'
import * as test from 'node:test'
import * as url from 'node:url'
import * as manifest from '../scripts/manifest.mjs'
import { project } from './helpers.mjs'

const triple = 'x86_64-unknown-linux-musl'
const file = 'gleam-v1.0.0-x86_64-unknown-linux-musl.tar.gz'
const body = 'archive'
const sha256 = crypto.createHash('sha256').update(body).digest('hex')

test.afterEach(() => test.mock.restoreAll())

// Serves a release from memory: the name of the asset is the last segment.
/** @param {Record<string, string>} assets */
function serve(assets) {
  return test.mock.method(
    globalThis,
    'fetch',
    async (/** @type {string} */ url) => {
      const asset = assets[String(url).split('/').pop() ?? '']
      return asset === undefined
        ? new Response('', { status: 404 })
        : new Response(asset)
    }
  )
}

test.describe('record', () => {
  test.it('skips a platform that has no archive', async () => {
    serve({})
    assert.equal(await manifest.record('1.0.0', triple, [], project({})), null)
  })

  test.it('records an archive without attestation as sha256-only', async () => {
    serve({ [file]: body, [`${file}.sha256`]: `${sha256} *${file}\n` })
    const asset = await manifest.record('1.0.0', triple, [file], project({}))
    assert.deepEqual(asset, { file, sha256, provenance: 'sha256-only' })
  })

  test.it(
    'refuses an archive that differs from the published checksum',
    async () => {
      serve({
        [file]: body,
        [`${file}.sha256`]: `${'0'.repeat(64)} *${file}\n`,
      })
      await assert.rejects(
        manifest.record('1.0.0', triple, [file], project({})),
        /sha256 mismatch/
      )
    }
  )

  test.it('records a verified attestation as sigstore', async () => {
    serve({
      [file]: body,
      [`${file}.sha256`]: `${sha256} *${file}\n`,
      [`${file}.sigstore`]: '{"signed":true}',
    })
    const calls = /** @type {unknown[][]} */ ([])
    const verify = async (/** @type {unknown[]} */ ...args) =>
      void calls.push(args)
    const available = [file, `${file}.sigstore`]
    const asset = await manifest.record(
      '1.0.0',
      triple,
      available,
      project({}),
      verify
    )
    assert.equal(asset?.provenance, 'sigstore')
    assert.deepEqual(calls, [['1.0.0', file, sha256, { signed: true }]])
  })

  test.it('records nothing when the attestation is refused', async () => {
    serve({
      [file]: body,
      [`${file}.sha256`]: `${sha256} *${file}\n`,
      [`${file}.sigstore`]: '{}',
    })
    const verify = async () => {
      throw new Error('refused')
    }
    const available = [file, `${file}.sigstore`]
    await assert.rejects(
      manifest.record('1.0.0', triple, available, project({}), verify),
      /refused/
    )
  })

  test.it('reports an asset that cannot be downloaded', async () => {
    serve({})
    await assert.rejects(
      manifest.record('1.0.0', triple, [file], project({})),
      /GitHub answered 404/
    )
  })
})

test.describe('compareVersions', () => {
  test.it('orders versions numerically, not as text', () => {
    const versions = ['1.10.0', '1.9.1', '1.2.0', '1.19.2', '1.9.0']
    assert.deepEqual(versions.sort(manifest.compareVersions), [
      '1.2.0',
      '1.9.0',
      '1.9.1',
      '1.10.0',
      '1.19.2',
    ])
  })
})

test.describe('write', () => {
  test.it(
    'writes a module that can be imported, sorted by version',
    async () => {
      const file = path.join(project({}), 'manifest.mjs')
      const asset = {
        file: 'a.tar.gz',
        sha256: 'abc',
        provenance: /** @type {const} */ ('sigstore'),
      }
      await manifest.write(
        { versions: { '1.10.0': { x: asset }, '1.9.0': { x: asset } } },
        file
      )
      const written = await import(
        `${url.pathToFileURL(file).href}?${Date.now()}`
      )
      assert.deepEqual(Object.keys(written.manifest.versions), [
        '1.9.0',
        '1.10.0',
      ])
      assert.match(fs.readFileSync(file, 'utf-8'), /^\/\/ Generated by scripts/)
    }
  )
})
